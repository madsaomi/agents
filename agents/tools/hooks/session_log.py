#!/usr/bin/env python3
"""
Stop-хук Claude Code: страховочная запись в agents/history/ (одна на сессию).

Регистрация: .claude/settings.json → Stop (срабатывает в конце каждого хода).
Логика идемпотентности:
  1) читает маркер .claude/.session_state.json (пишет inject_context.py на SessionStart);
  2) если агент уже сам создал/обновил запись в agents/history/ после старта сессии — выходим;
  3) если запись за эту сессию уже создана хуком — выходим;
  4) иначе создаёт заготовку session_YYYY-MM-DD_HH-mm_claude-code.md (её дополнит агент).
Никогда не перезаписывает существующие записи (правило ANTI_PATTERNS №2).
"""

import json
import re
import sys
from datetime import datetime
from pathlib import Path


def project_root() -> Path:
    import os
    env = os.environ.get("CLAUDE_PROJECT_DIR")
    if env:
        return Path(env)
    return Path(__file__).resolve().parents[3]


def main() -> int:
    try:
        inp = json.loads(sys.stdin.read() or "{}")
    except Exception:
        return 0

    root = project_root()
    state_path = root / ".claude" / ".session_state.json"
    if not state_path.is_file():
        return 0  # маркера нет — не гадаем, выходим тихо
    try:
        state = json.loads(state_path.read_text(encoding="utf-8"))
    except Exception:
        return 0

    session_id = inp.get("session_id", "")
    if state.get("session_id") and session_id and state["session_id"] != session_id:
        return 0  # маркер от другой сессии

    # Уже создана запись этой сессии? (по маркеру в имени файла)
    marker_re = re.compile(r"session_\d{4}-\d{2}-\d{2}_\d{2}-\d{2}_claude-code\.md$")
    history = root / "agents" / "history"
    if history.is_dir():
        for f in history.glob("session_*_claude-code.md"):
            if marker_re.search(f.name):
                return 0  # хук уже сработал в этой сессии

        # Агент уже сам написал историю после старта сессии?
        started = state.get("started_at", "")
        if started:
            try:
                started_ts = datetime.fromisoformat(started).timestamp()
            except ValueError:
                started_ts = 0.0
            for f in history.glob("*.md"):
                if f.name == "README.md":
                    continue
                try:
                    if f.stat().st_mtime >= started_ts:
                        return 0  # агент сам зафиксировал сессию
                except OSError:
                    continue

        # Создаём заготовку (append-only: новый файл, ничего не перезаписываем)
        now = datetime.now()
        stub = history / f"session_{now.strftime('%Y-%m-%d_%H-%M')}_claude-code.md"
        n = 1
        while stub.exists():
            stub = history / f"session_{now.strftime('%Y-%m-%d_%H-%M')}-{n:02d}_claude-code.md"
            n += 1
        stub.write_text(
            f"""# 📝 Отчет о сессии: {now.strftime('%Y-%m-%d %H:%M')} (autogenerated by Stop-hook)

> **Инструмент:** Claude Code (Stop-хук, автозаготовка)
> **Статус:** 🔵 Требует дополнения агентом в конце сессии

## ✅ Что сделано:
- *(хук создал заготовку автоматически — дополни реальными результатами)*

## ⏭ Следующий шаг для агента:
- Продолжить с первого невыполненного шага в `agents/tasks/active_task.md`.

## 📌 Связанные артефакты:
- План: `agents/plans/`
- Задача: `agents/tasks/active_task.md`
""",
            encoding="utf-8",
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
